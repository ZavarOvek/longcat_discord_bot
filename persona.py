    zzz_mode_prompt: str
    # Шапка блоку авто-контексту ZZZ (підкладка перевірених даних з бази).
    zzz_reference_header: str
    # Текст коригувального ретраю мовного вартового (cogs/chat.py).
    lang_guard_retry_note: str



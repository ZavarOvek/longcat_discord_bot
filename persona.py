    # блок підклеюється до останньої репліки користувача.
    trailing_reminder: str
    # «Надгробок пам'яті»: лишається першим у історії після /reset, щоб бот знав
    # про амнезію і не підтверджував чуже «ти ж казав учора».
    reset_marker: str
    # Корекційний ретрай санітайзера розмітки tool-викликів (llm/tools.py).

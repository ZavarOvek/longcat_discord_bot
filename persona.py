PERSONA_KEYS = tuple(field.name for field in fields(Persona))


def _die(message: str) -> NoReturn:
    print(f"[config] {message}", file=sys.stderr)
    raise SystemExit(1)


def load_persona(path: str) -> Persona:
    """Персона з TOML-файлу; немає файлу — вбудовані дефолти.

    Кожен ключ необов'язковий і перекриває лише своє поле. Невідомий ключ,
    нерядкове значення або чужий плейсхолдер у zzz_mode_prompt — зрозуміле
    падіння на старті, а не тиха підстановка дефолту."""
    file = Path(path)
    if not file.is_file():
        return DEFAULT_PERSONA

    try:
        raw = tomllib.loads(file.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        _die(f"не можу прочитати файл персони {path}: {exc}")

    unknown = sorted(set(raw) - set(PERSONA_KEYS))
    if unknown:
        _die(
            f"невідомий ключ у файлі персони {path}: {', '.join(unknown)}. "
            f"Допустимі ключі: {', '.join(PERSONA_KEYS)}"
        )

    for key, value in raw.items():
        if not isinstance(value, str):
            _die(f"ключ {key} у файлі персони {path} має бути рядком, а не {type(value).__name__}")

    persona = replace(DEFAULT_PERSONA, **raw)

    # Єдиний текст, що проходить через .format(): чужий плейсхолдер або одинока
    # фігурна дужка інакше впали б у рантаймі на першому ж /mode zzz.
    try:
        persona.zzz_mode_prompt.format(version="x")
    except (KeyError, IndexError, ValueError) as exc:
        _die(
            f"у ключі zzz_mode_prompt (файл персони {path}) дозволений лише плейсхолдер "
            f"{{version}}; решту фігурних дужок подвоюй ({{{{ і }}}}). Деталі: {exc!r}"
        )

    return persona
